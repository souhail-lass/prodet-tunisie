type ProductDraft = Omit<Product, 'image' | 'contextImages' | 'featured'> &
  Partial<Pick<Product, 'image' | 'contextImages' | 'featured'>>;

function createProduct(product: ProductDraft): Product {
  const primaryUseCase = product.useCases[0] ?? 'sols';
  const visual = visualsByUseCase[primaryUseCase];

  return {
    ...product,
    image: product.image ?? visual.image,
    contextImages: product.contextImages ?? visual.contextImages,
    featured: product.featured ?? false,
  };
}

